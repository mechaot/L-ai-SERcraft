"""Generate third-party notices for the Rust dependencies of the workspace.

Usage: python3 -I tools/gen_third_party.py [--md OUT] [--texts OUT]
  --md OUT     Markdown table: crate, version, license expression, repository.
  --texts OUT  One text file: per package a header plus every LICENSE*/LICENCE*/COPYING*/NOTICE*
               file found next to its Cargo.toml.

Source: `cargo metadata --format-version 1 --locked` in the repo root. Packages = every non-workspace
package reachable from the workspace members over normal and build dependencies (dev-only
dependencies are skipped). All target platforms are included (Linux, Windows, macOS), not only
the host.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LICENSE_PREFIXES = ("license", "licence", "copying", "notice")


def load_metadata() -> dict:
    """Run `cargo metadata` in the repo root.

    Returns the parsed JSON document. Exits with the cargo error text on failure.
    """
    proc = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, capture_output=True, text=True, check=False,
    )
    if proc.returncode != 0:
        sys.exit(f"cargo metadata failed:\n{proc.stderr}")
    return json.loads(proc.stdout)


def third_party_packages(meta: dict) -> list[dict]:
    """Collect non-workspace packages reachable over normal + build dependencies.

    meta: parsed `cargo metadata` output. Returns package dicts sorted by (name, version).
    """
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    seen: set[str] = set()
    stack = list(members)
    while stack:
        cur = stack.pop()
        for dep in nodes[cur]["deps"]:
            # keep the edge only if some dep kind is normal (None) or build
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if not kinds & {None, "build"}:
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    pkgs = [by_id[i] for i in seen if i not in members]
    return sorted(pkgs, key=lambda p: (p["name"].lower(), p["version"]))


def license_files(pkg: dict) -> list[Path]:
    """Find license-like files next to the package manifest.

    pkg: package dict from cargo metadata. Returns sorted file paths (may be empty).
    """
    base = Path(pkg["manifest_path"]).parent
    found = [f for f in base.iterdir() if f.is_file() and f.name.lower().startswith(LICENSE_PREFIXES)]
    return sorted(found, key=lambda f: f.name)


def write_md(pkgs: list[dict], out: Path) -> None:
    """Write the Markdown table.

    pkgs: packages from `third_party_packages`. out: target file.
    """
    lines = [
        "# Third-party Rust dependencies",
        "",
        "Generated by `tools/gen_third_party.py` from `Cargo.lock`. Do not edit by hand.",
        f"{len(pkgs)} packages (normal and build dependencies of the workspace, all target platforms).",
        "License texts: `THIRD_PARTY_LICENSES.txt` in release packages. Other credits: [NOTICE.md](NOTICE.md).",
        "",
        "| Crate | Version | License | Repository |",
        "|---|---|---|---|",
    ]
    for p in pkgs:
        lic = (p.get("license") or p.get("license_file") or "unknown").replace("|", "\\|")
        repo = p.get("repository") or p.get("homepage") or ""
        lines.append(f"| {p['name']} | {p['version']} | {lic} | {repo} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_texts(pkgs: list[dict], out: Path) -> None:
    """Write the combined license text file.

    pkgs: packages from `third_party_packages`. out: target file.
    """
    parts = [
        "THIRD-PARTY LICENSES OF THE RUST DEPENDENCIES OF L-ai-SERctrl\n"
        "Generated by tools/gen_third_party.py. Other credits: NOTICE.md.\n"
    ]
    bar = "=" * 78
    for p in pkgs:
        lic = p.get("license") or p.get("license_file") or "unknown"
        head = [bar, f"{p['name']} {p['version']}", f"license: {lic}"]
        if p.get("repository"):
            head.append(f"repository: {p['repository']}")
        head.append(bar)
        files = license_files(p)
        if not files:
            body = [f"no license file found, license: {lic}"]
        else:
            body = []
            for f in files:
                body.append(f"--- {f.name} ---")
                body.append(f.read_text(encoding="utf-8", errors="replace").rstrip())
                body.append("")
        parts.append("\n".join(head + body) + "\n")
    out.write_text("\n".join(parts), encoding="utf-8")


def main() -> int:
    """CLI entry point.

    Returns the process exit code (0 on success, 2 when no output option is given).
    """
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--md", type=Path, help="write Markdown table here")
    ap.add_argument("--texts", type=Path, help="write combined license texts here")
    args = ap.parse_args()
    if not args.md and not args.texts:
        ap.error("give --md and/or --texts")
    pkgs = third_party_packages(load_metadata())
    if args.md:
        write_md(pkgs, args.md)
    if args.texts:
        write_texts(pkgs, args.texts)
    print(f"{len(pkgs)} packages", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
