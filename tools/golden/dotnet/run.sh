#!/usr/bin/env bash
# Regenerate tests/golden/dotnet/*.tsv with Mono and the unicode range table for lg-dotnet.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
source "$root/../.mono-build/env.sh"
out="$root/tests/golden/dotnet"
tmp="$(mktemp -d)"
mcs -out:"$tmp/GenDotnet.exe" "$here/GenDotnet.cs"
HOME="$tmp" mono "$tmp/GenDotnet.exe" "$out"
# Emit Rust range table from chars.tsv (BMP only, .NET char is a UTF-16 unit).
gen="$root/crates/dotnet/src/unicode_tables.rs"
{
  echo "//! GENERATED by tools/golden/dotnet/run.sh from Mono Char.IsLetter/IsDigit/IsNumber/IsWhiteSpace. Do not edit."
  for k in letter digit number white; do
    up=$(echo "$k" | tr a-z A-Z)
    echo "/// Inclusive BMP ranges where Char.Is${k^}() is true."
    echo "pub(crate) static ${up}_RANGES: &[(u16, u16)] = &["
    awk -F'\t' -v k="$k" '$1==k {printf "    (0x%s, 0x%s),\n", toupper($2), toupper($3)}' "$out/chars.tsv"
    echo "];"
  done
} > "$gen"
rm -rf "$tmp"
